// Writes src/views/icons.ts: the Material Symbols (outlined, weight 400, @material-symbols/svg-400) the admin page uses,
// as the inside of their SVG, so the page draws them inline: no font, nothing loaded from Google. Run it after changing
// NAMES: yarn icons.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const NAMES = [
  'add', 'admin_panel_settings', 'block', 'cancel', 'check', 'check_circle', 'computer', 'content_copy', 'delete',
  'devices', 'download', 'edit', 'error', 'group', 'info', 'key', 'key_off', 'lock_open', 'lock_reset', 'login', 'logout',
  'password', 'person', 'search', 'sync', 'sync_disabled', 'visibility', 'visibility_off', 'warning',
];

const require = createRequire(import.meta.url);
const icons = NAMES.map((name) => {
  const svg = readFileSync(require.resolve(`@material-symbols/svg-400/outlined/${name}.svg`), 'utf8');
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1].trim();
  if (!inner) throw new Error(`${name}.svg: no <svg>`);
  return `  ${/^[a-z_]+$/.test(name) ? name : `'${name}'`}: '${inner.replace(/'/g, "\'")}',`;
});
writeFileSync(
  new URL('../src/views/icons.ts', import.meta.url),
  `// Generated by scripts/icons.mjs (yarn icons) from @material-symbols/svg-400, outlined: do not edit.\n` +
    `// Material Symbols are by Google, Apache License 2.0.\n` +
    `export const ICONS = {\n${icons.join('\n')}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log(`${NAMES.length} icons -> src/views/icons.ts`);
