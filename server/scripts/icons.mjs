// Writes src/views/icons.ts: the Lucide icons (lucide-static) the admin page uses, as the inside of their SVG, so the
// page draws them inline (views/layout.tsx#Icon sets the stroke): no font, nothing loaded from elsewhere. Run it after
// changing NAMES: yarn icons.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const NAMES = [
  'calendar', 'check', 'chevron-down', 'circle-alert', 'circle-check', 'clock', 'copy', 'download', 'ellipsis-vertical',
  'eye', 'eye-off', 'globe', 'key-round', 'lock', 'lock-open', 'log-in', 'log-out', 'monitor', 'pencil', 'plus', 'save',
  'search', 'shield-check', 'sparkles', 'trash-2', 'triangle-alert', 'unlink', 'user', 'users', 'x',
];

const require = createRequire(import.meta.url);
const icons = NAMES.map((name) => {
  const svg = readFileSync(require.resolve(`lucide-static/icons/${name}.svg`), 'utf8');
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1].replace(/\s*\n\s*/g, ' ').trim();
  if (!inner) throw new Error(`${name}.svg: no <svg>`);
  return `  '${name}': '${inner.replace(/'/g, "\\'")}',`;
});
writeFileSync(
  new URL('../src/views/icons.ts', import.meta.url),
  `// Generated by scripts/icons.mjs (yarn icons) from lucide-static: do not edit.\n` +
    `// Lucide icons are ISC licensed (https://lucide.dev/license).\n` +
    `export const ICONS = {\n${icons.join('\n')}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log(`${NAMES.length} icons -> src/views/icons.ts`);
