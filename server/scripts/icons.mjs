// Writes src/views/icons.ts: the Phosphor icons (@phosphor-icons/core) the admin page uses, regular and duotone, as the
// inside of their SVG, so the page draws them inline (views/layout.tsx#Icon): no font, nothing loaded from elsewhere.
// The page names them as before (the keys of NAMES); the values are Phosphor's names. Run it after changing NAMES:
// yarn icons.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const NAMES = {
  calendar: 'calendar-blank',
  check: 'check',
  'chevron-down': 'caret-down',
  'circle-alert': 'warning-circle',
  'circle-check': 'check-circle',
  clock: 'clock',
  copy: 'copy',
  download: 'download-simple',
  'ellipsis-vertical': 'dots-three-vertical',
  eye: 'eye',
  'eye-off': 'eye-slash',
  globe: 'globe-simple',
  'key-round': 'key',
  lock: 'lock-simple',
  'lock-open': 'lock-simple-open',
  'log-in': 'sign-in',
  'log-out': 'sign-out',
  monitor: 'desktop',
  pencil: 'pencil-simple',
  plus: 'plus',
  save: 'floppy-disk',
  search: 'magnifying-glass',
  'shield-check': 'shield-check',
  sparkles: 'sparkle',
  'trash-2': 'trash',
  'triangle-alert': 'warning',
  unlink: 'link-break',
  user: 'user',
  users: 'users',
  x: 'x',
};

const require = createRequire(import.meta.url);
const inner = (file) => {
  const svg = readFileSync(require.resolve(`@phosphor-icons/core/assets/${file}`), 'utf8');
  const body = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1].replace(/\s*\n\s*/g, ' ').trim();
  if (!body) throw new Error(`${file}: no <svg>`);
  return body.replace(/'/g, "\\'");
};
const lines = (weight) =>
  Object.entries(NAMES).map(([name, file]) => `  '${name}': '${inner(weight === 'regular' ? `regular/${file}.svg` : `duotone/${file}-duotone.svg`)}',`);
writeFileSync(
  new URL('../src/views/icons.ts', import.meta.url),
  `// Generated by scripts/icons.mjs (yarn icons) from @phosphor-icons/core: do not edit.\n` +
    `// Phosphor Icons are MIT licensed (https://phosphoricons.com).\n` +
    `export const ICONS = {\n${lines('regular').join('\n')}\n} as const;\n\n` +
    `/** The same icons in two tones (the second layer at 20 % opacity), for the stat cards and empty lists. */\n` +
    `export const DUOTONE: Record<IconName, string> = {\n${lines('duotone').join('\n')}\n};\n\n` +
    `export type IconName = keyof typeof ICONS;\n`,
);
console.log(`${Object.keys(NAMES).length} icons (regular, duotone) -> src/views/icons.ts`);
